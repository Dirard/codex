#!/usr/bin/env bash
# Differential check of the generated Go protocol codecs against a previous
# generated package (specs/go-sdk-decode-perf-2026-10-25.md, UC6).
#
# Extracts sdk/go/protocol (without tests) at a pinned revision into the
# temporary package sdk/go/internal/protocodex/legacyprotocol, generates a
# registry of every type both packages decode, and runs the codecdiff-tagged
# tests in internal/protocodex: schema instances and their mutations for every
# type, lockstep-perturbed marshals, DecodeServerNotificationPayload for every
# notification, then optionally the fuzz target. The temporary files are
# removed on exit.
#
#   scripts/fork/go-codec-diff.sh [-- GO_TEST_ARGS...]
#
# Environment:
#   CODEC_DIFF_LEGACY_REV   revision with the previous codec (default: the last
#                           commit before the alias-struct codec)
#   CODEC_DIFF_FUZZTIME     also run FuzzCodecMatchesLegacy for this long
#                           (for example 10m); unset skips fuzzing
#   CODEC_DIFF_INSTANCES    schema instances per type (default 12)
#
# The check is for a codec migration: once the protocol changes after the
# pinned revision, the old package no longer has the same fields, so it is not
# part of CI.

set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
go_dir="${repo_root}/sdk/go"
legacy_rev="${CODEC_DIFF_LEGACY_REV:-1e2dca94fe}"
legacy_rel="internal/protocodex/legacyprotocol"
legacy_dir="${go_dir}/${legacy_rel}"
registry="${go_dir}/internal/protocodex/codec_diff_registry_test.go"

die() {
  printf 'go-codec-diff: %s\n' "$*" >&2
  exit 1
}

[[ ! -e "${legacy_dir}" && ! -e "${registry}" ]] ||
  die "${legacy_rel} or $(basename "${registry}") already exists; remove it or let a running check finish"

cleanup() {
  rm -rf -- "${legacy_dir}" "${registry}"
}
trap cleanup EXIT

git -C "${repo_root}" rev-parse --verify --quiet "${legacy_rev}^{commit}" >/dev/null ||
  die "unknown revision ${legacy_rev}"

mkdir -p "${legacy_dir}"
count=0
while IFS= read -r path; do
  [[ "${path}" == *.go && "${path}" != *_test.go ]] || continue
  git -C "${repo_root}" show "${legacy_rev}:${path}" |
    sed 's/^package protocol$/package legacyprotocol/' >"${legacy_dir}/$(basename "${path}")"
  count=$((count + 1))
done < <(git -C "${repo_root}" ls-tree --name-only "${legacy_rev}" sdk/go/protocol/)
((count > 0)) || die "no sdk/go/protocol sources at ${legacy_rev}"

# Types with an UnmarshalJSON method in both packages, sorted.
decoded_types() {
  grep -hoE '^func \(v \*[A-Za-z0-9_]+\) UnmarshalJSON\(' "$1"/*.go |
    sed -E 's/^func \(v \*([A-Za-z0-9_]+)\).*/\1/' | LC_ALL=C sort -u
}
types="$(LC_ALL=C comm -12 <(decoded_types "${go_dir}/protocol") <(decoded_types "${legacy_dir}"))"
[[ -n "${types}" ]] || die "no shared decoded types"

{
  printf '//go:build codecdiff\n\n'
  printf '// Code generated by scripts/fork/go-codec-diff.sh from %s; DO NOT EDIT.\n\n' "${legacy_rev}"
  printf 'package protocodex\n\n'
  printf 'import (\n\t"github.com/openai/codex/sdk/go/%s"\n\t"github.com/openai/codex/sdk/go/protocol"\n)\n\n' "${legacy_rel}"
  printf 'const codecDiffLegacyRev = "%s"\n\n' "${legacy_rev}"
  printf 'var codecDiffTypes = []codecDiffType{\n'
  while IFS= read -r name; do
    printf '\t{name: "%s", fresh: func() any { return new(protocol.%s) }, legacy: func() any { return new(legacyprotocol.%s) }},\n' \
      "${name}" "${name}" "${name}"
  done <<<"${types}"
  printf '}\n'
} >"${registry}"
gofmt -w "${registry}"

printf 'go-codec-diff: %d legacy files from %s, %d shared types\n' "${count}" "${legacy_rev}" "$(grep -c . <<<"${types}")"

extra=()
if [[ "${1:-}" == "--" ]]; then
  shift
  extra=("$@")
fi

cd "${go_dir}"
go test -tags codecdiff -count=1 -run '^TestCodecMatchesLegacy' -v "${extra[@]}" ./internal/protocodex/
if [[ -n "${CODEC_DIFF_FUZZTIME:-}" ]]; then
  go test -tags codecdiff -run '^$' -fuzz '^FuzzCodecMatchesLegacy$' -fuzztime "${CODEC_DIFF_FUZZTIME}" ./internal/protocodex/
fi
