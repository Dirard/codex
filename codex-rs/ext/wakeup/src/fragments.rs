//! Model-visible text of scheduled wakeups: tool outputs, the wake input, the loop context
//! and cancel notices (`specs/scheduled-wakeups-2026-11-07.md`, Data of UC2–UC5).

use chrono::DateTime;
use chrono::SecondsFormat;
use chrono::Utc;
use codex_core::config::ScheduledWakeupsConfig;
use codex_utils_string::untrusted::UntrustedBoundary;

use crate::state::CancelReason;
